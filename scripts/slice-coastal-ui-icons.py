"""Slice original imagegen atlases; keep generated silhouettes and alpha intact."""
import json,hashlib,re
from pathlib import Path
from collections import deque
from PIL import Image,ImageFilter,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'output/imagegen/coastal-ui-v3'
PUBLIC=ROOT/'public/icons/coastal-ui-v3'
def sheet_components(im, columns, rows):
    # Generated grids are approximate: recover whole connected shapes before
    # assigning their centers to slots, so tails/ears cannot be cut by a grid line.
    alpha=im.getchannel('A'); w,h=im.size
    solid=alpha.point(lambda a:255 if a>=32 else 0)
    px=solid.load(); seen=bytearray(w*h); groups=[[] for _ in range(columns*rows)]
    for y in range(h):
        for x in range(w):
            if not px[x,y] or seen[y*w+x]: continue
            q=deque([(x,y)]); seen[y*w+x]=1; component=[]
            x0=x1=x; y0=y1=y
            while q:
                cx,cy=q.popleft();component.append((cx,cy))
                x0=min(x0,cx);x1=max(x1,cx);y0=min(y0,cy);y1=max(y1,cy)
                for nx,ny in [(cx-1,cy),(cx+1,cy),(cx,cy-1),(cx,cy+1)]:
                    if 0<=nx<w and 0<=ny<h and px[nx,ny] and not seen[ny*w+nx]:
                        seen[ny*w+nx]=1;q.append((nx,ny))
            if len(component)<16:continue
            col=min(columns-1,int((x0+x1)/2/w*columns))
            row=min(rows-1,int((y0+y1)/2/h*rows))
            groups[row*columns+col].append(component)
    anchors=[]
    for group in groups:
        core=max(group,key=len)
        xs,ys=zip(*core)
        anchors.append(((min(xs)+max(xs))/2,(min(ys)+max(ys))/2))
    regrouped=[[] for _ in anchors]
    for group in groups:
        for comp in group:
            xs,ys=zip(*comp);cx=(min(xs)+max(xs))/2;cy=(min(ys)+max(ys))/2
            nearest=min(range(len(anchors)),key=lambda i:((cx-anchors[i][0])/w)**2+((cy-anchors[i][1])/h)**2)
            regrouped[nearest].append(comp)
    groups=regrouped
    result=[]
    for components in groups:
        if not components:raise ValueError('Empty icon slot')
        threshold=max(16,max(map(len,components))*.0015)
        mask=Image.new('L',im.size); mp=mask.load()
        for comp in components:
            if len(comp)>=threshold:
                for x,y in comp:mp[x,y]=255
        mask=mask.filter(ImageFilter.MaxFilter(5))
        a=alpha.copy();a.putdata([v if m and v>=8 else 0 for v,m in zip(a.getdata(),mask.getdata())])
        icon=im.copy();icon.putalpha(a);box=a.getbbox()
        result.append((icon.crop(box),box))
    return result

entries=[]
for group in json.loads((OUT/'layout.json').read_text()):
    source=OUT/'sheets'/f"{group['sheet']}.png"
    im=Image.open(source).convert('RGBA')
    for name,(icon,bbox) in zip(group['icons'],sheet_components(im,4,4)):
        for size in [256,128,64]:
            directory=PUBLIC if size==256 else OUT/f'png-{size}'
            directory.mkdir(parents=True,exist_ok=True)
            fitted=icon.copy();fitted.thumbnail((round(size*.84),round(size*.84)),Image.Resampling.LANCZOS)
            canvas=Image.new('RGBA',(size,size));canvas.alpha_composite(fitted,((size-fitted.width)//2,(size-fitted.height)//2))
            canvas.save(directory/f'{name}.png',optimize=True)
        entries.append(dict(name=name,sheet=group['sheet'],sourceSize=list(im.size),sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),contentBox=list(bbox),url=f'/icons/coastal-ui-v3/{name}.png',sha256=hashlib.sha256((PUBLIC/f'{name}.png').read_bytes()).hexdigest()))
(OUT/'manifest.json').write_text(json.dumps(dict(generator='Codex built-in imagegen',count=len(entries),sizes=[256,128,64],icons=entries),indent=2))
mapping=ROOT/'src/icons/generated.ts';text=mapping.read_text()
for entry in entries:
    text=re.sub(r'("'+entry['name']+r'": )"[^"]+"',lambda m:m[1]+json.dumps(entry['url']),text)
text=re.sub(r'("ball-poke": )"[^"]+"',r'\1"/icons/coastal-ui-v3/pokeball.png"',text)
text=text.replace('// Generated by scripts/slice-swsh-icons.py from the reviewed imagegen sheets.','// Original teaching art plus reviewed coastal-ui-v3 imagegen UI icons. See output/imagegen/coastal-ui-v3/manifest.json.')
mapping.write_text(text)
font=ImageFont.truetype('/System/Library/Fonts/Menlo.ttc',13)
for theme,bg in [('cream','#f6f1df'),('forest','#243b32')]:
    sheet=Image.new('RGB',(1120,((len(entries)+7)//8)*146),bg);d=ImageDraw.Draw(sheet)
    for i,e in enumerate(entries):
        x,y=(i%8)*140,(i//8)*146
        icon=Image.open(PUBLIC/f"{e['name']}.png");icon.thumbnail((112,112),Image.Resampling.LANCZOS)
        sheet.paste(icon,(x+14,y+5),icon)
        d.text((x+70,y+122),e['name'],font=font,fill='#514634' if theme=='cream' else '#fff7e4',anchor='mt')
    sheet.save(OUT/f'contact-sheet-{theme}.png')
print(json.dumps(dict(count=len(entries),totalBytes=sum(p.stat().st_size for p in PUBLIC.glob('*.png')))))
