import assert from 'node:assert/strict';
import {advanceCare,careRequest,careState,comfortCompanion,deferCare,nextCareRequest} from '../src/lib/companionCare';
import type {Capture} from '../src/types';
const c:Capture={id:25,caughtAt:0,ball:'poke',friendship:10};
assert.equal(careRequest(c),null,'existing saves start gently');
assert.equal(c.care,undefined,'reading needs must not mutate saves');
for(let i=0;i<11;i++)advanceCare(c,10);
assert.equal(careRequest(c)?.kind,'feed');
const original=JSON.parse(JSON.stringify(c));
assert.deepEqual(careState(JSON.parse(JSON.stringify(c))),careState(c),'save round-trip preserves timers');
comfortCompanion(c,'feed');assert.equal(careRequest(c),null);
for(let i=0;i<5;i++)advanceCare(c,10);
assert.equal(careRequest(c)?.kind,'pet','a later invitation can request companionship');
comfortCompanion(c,'pet');assert.equal(careRequest(c),null);
const hungry=structuredClone(original);deferCare(hungry);assert.equal(careRequest(hungry),null);
for(let i=0;i<9;i++)advanceCare(hungry,10);assert.equal(careRequest(hungry)?.kind,'feed');
const before=careState(hungry).seconds;advanceCare(hungry,1000000);assert.equal(careState(hungry).seconds,before+10,'resuming never accumulates offline debt');
const second={...structuredClone(original),id:133};assert.equal(nextCareRequest([hungry,second])?.id,25);
assert.equal(c.friendship,10,'care never grants or removes currency or friendship by itself');
assert.equal(nextCareRequest([]),null);assert.equal(careRequest(undefined),null);
console.log('PASS: old saves, staggered requests, feeding, companionship, quiet periods, defer, save round-trip, bounded time and single invitation.');
