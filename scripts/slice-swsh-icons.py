"""Slice the imagegen sheets, retain alpha, normalize padding, and export PNG sizes."""
import json, hashlib
from pathlib import Path
from collections import deque
from PIL import Image, ImageFilter, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'output/imagegen/swsh-icons'
PUBLIC=ROOT/'public/icons/swsh'
layout=json.loads((OUT/'layout.json').read_text())

def sheet_components(im, columns, rows):
    # Generated grids are approximate: recover whole connected shapes before
    # assigning their centers to slots, so tails/ears cannot be cut by a grid line.
    alpha=im.getchannel('A'); w,h=im.size
    solid=alpha.point(lambda a:255 if a>=32 else 0)
    px=solid.load(); seen=bytearray(w*h); groups=[[] for _ in range(columns*rows)]
    for y in range(h):
        for x in range(w):
            if not px[x,y] or seen[y*w+x]: continue
            q=deque([(x,y)]); seen[y*w+x]=1; component=[]
            x0=x1=x; y0=y1=y
            while q:
                cx,cy=q.popleft();component.append((cx,cy))
                x0=min(x0,cx);x1=max(x1,cx);y0=min(y0,cy);y1=max(y1,cy)
                for nx,ny in [(cx-1,cy),(cx+1,cy),(cx,cy-1),(cx,cy+1)]:
                    if 0<=nx<w and 0<=ny<h and px[nx,ny] and not seen[ny*w+nx]:
                        seen[ny*w+nx]=1;q.append((nx,ny))
            if len(component)<16:continue
            col=min(columns-1,int((x0+x1)/2/w*columns))
            row=min(rows-1,int((y0+y1)/2/h*rows))
            groups[row*columns+col].append(component)
    result=[]
    for components in groups:
        if not components:raise ValueError('Empty icon slot')
        threshold=max(16,max(map(len,components))*.0015)
        mask=Image.new('L',im.size); mp=mask.load()
        for comp in components:
            if len(comp)>=threshold:
                for x,y in comp:mp[x,y]=255
        mask=mask.filter(ImageFilter.MaxFilter(5))
        a=alpha.copy();a.putdata([v if m and v>=8 else 0 for v,m in zip(a.getdata(),mask.getdata())])
        icon=im.copy();icon.putalpha(a);box=a.getbbox()
        result.append((icon.crop(box),box))
    return result

entries=[]; warnings=[]; app_source=None
for group in layout:
    source=OUT/'sheets'/f"{group['sheet']}.png"
    im=Image.open(source).convert('RGBA'); w,h=im.size
    extracted=sheet_components(im,group['columns'],group['rows'])
    for i,name in enumerate(group['icons']):
        col,row=i%group['columns'],i//group['columns']
        rect=(round(col*w/group['columns']),round(row*h/group['rows']),round((col+1)*w/group['columns']),round((row+1)*h/group['rows']))
        icon,bbox=extracted[i]
        entry_source=source; source_size=[w,h]
        revision=OUT/'revisions'/f'{name}.png'
        if revision.exists():
            revised=Image.open(revision).convert('RGBA')
            icon,bbox=sheet_components(revised,1,1)[0]
            entry_source=revision;source_size=list(revised.size)
            rect=(0,0,*revised.size)
        if name=='app-icon':app_source=icon.copy()
        if bbox[0]<2 or bbox[1]<2 or bbox[2]>source_size[0]-2 or bbox[3]>source_size[1]-2:warnings.append({'name':name,'cell':rect,'bbox':bbox})
        for size in [256,128,64]:
            directory=PUBLIC if size==256 else OUT/f'png-{size}'
            directory.mkdir(parents=True,exist_ok=True)
            fitted=icon.copy(); fitted.thumbnail((round(size*.86),round(size*.86)),Image.Resampling.LANCZOS)
            canvas=Image.new('RGBA',(size,size));canvas.alpha_composite(fitted,((size-fitted.width)//2,(size-fitted.height)//2))
            canvas.save(directory/f'{name}.png',optimize=True)
        entries.append({'name':name,'sheet':str(entry_source.relative_to(ROOT)),'sourceSize':source_size,'cell':list(rect),'contentBox':list(bbox),'url':f'/icons/swsh/{name}.png','sha256':hashlib.sha256((PUBLIC/f'{name}.png').read_bytes()).hexdigest()})
# Sheet artwork is retained separately at its actual generated resolution, never claimed to be 2K.
(OUT/'manifest.json').write_text(json.dumps({'generator':'Codex built-in imagegen','count':len(entries),'sizes':[256,128,64],'warnings':warnings,'icons':entries},ensure_ascii=False,indent=2))
(ROOT/'src/icons/generated.ts').write_text('// Generated by scripts/slice-swsh-icons.py from the reviewed imagegen sheets.\nexport const ICON_ASSETS: Record<string, string> = '+json.dumps({e['name']:e['url'] for e in entries},indent=2)+';\n')
# Contact sheet: labels are external to the delivered transparent PNGs.
font=ImageFont.truetype('/System/Library/Fonts/Menlo.ttc',13)
cols=10; cw,ch=140,146; rows=(len(entries)+cols-1)//cols
sheet=Image.new('RGB',(cols*cw,rows*ch+88),'#f2f4f8'); d=ImageDraw.Draw(sheet)
d.rectangle((0,0,cols*cw,72),fill='#e7354c')
d.text((24,20),'POKEPAL / SWORD & SHIELD INSPIRED ICONS',font=ImageFont.truetype('/System/Library/Fonts/Menlo.ttc',26),fill='white')
for i,e in enumerate(entries):
    x,y=(i%cols)*cw,(i//cols)*ch+88
    d.rounded_rectangle((x+6,y+2,x+cw-6,y+ch-6),radius=12,fill='white')
    icon=Image.open(PUBLIC/f"{e['name']}.png");icon.thumbnail((100,100),Image.Resampling.LANCZOS)
    sheet.paste(icon,(x+20,y+8),icon)
    d.text((x+cw/2,y+116),e['name'],font=font,fill='#303746',anchor='mt')
sheet.save(OUT/'contact-sheet.png')
# PWA app icons use the generated emblem on an opaque white install-icon canvas.
assert app_source is not None
app=app_source
for size in [192,512]:
    canvas=Image.new('RGBA',(size,size),'#ffffff')
    icon=app.copy();icon.thumbnail((round(size*.84),round(size*.84)),Image.Resampling.LANCZOS)
    canvas.alpha_composite(icon,((size-icon.width)//2,(size-icon.height)//2))
    canvas.convert('RGB').save(ROOT/f'public/icons/icon-{size}.png',optimize=True)
print(json.dumps({'count':len(entries),'warnings':warnings},indent=2))
